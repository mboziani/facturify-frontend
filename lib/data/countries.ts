// Helper function to get country by code
export const getCountryByCode = (code: string): Country | undefined => {
    return COUNTRIES.find(c => c.code === code);
};

// Helper function to get countries by region
export const getCountriesByRegion = (region: Country['region']): Country[] => {
    return COUNTRIES.filter(c => c.region === region);
};

// Helper function to get all unique currencies
export const getAllCurrencies = (): string[] => {
    return Array.from(new Set(COUNTRIES.map(c => c.currency))).sort();
};
